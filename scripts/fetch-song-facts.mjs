#!/usr/bin/env node
/**
 * Build src/data/songFacts.ts from REAL YouTube Data API v3 data.
 *
 * Reads the catalog videoIds out of src/data/videos.ts, then fetches
 * contentDetails (duration) + snippet (publishedAt, description) for each.
 * Requires YOUTUBE_API_KEY in the environment (never committed).
 * Quota cost: 1 unit per 50-video batch — effectively free.
 *
 * Run:  YOUTUBE_API_KEY=... node scripts/fetch-song-facts.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const apiKey = process.env.YOUTUBE_API_KEY;
if (!apiKey) {
  console.error("YOUTUBE_API_KEY is not set — aborting.");
  process.exit(1);
}

const videosSrc = readFileSync(join(root, "src/data/videos.ts"), "utf8");
const ids = [...videosSrc.matchAll(/videoId:\s*"([A-Za-z0-9_-]{11})"/g)].map((m) => m[1]);
const uniqueIds = [...new Set(ids)];
console.log(`Catalog videoIds found: ${uniqueIds.length}`);

function iso8601ToSeconds(iso) {
  const m = /^PT(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?$/.exec(iso ?? "");
  if (!m) return null;
  return (Number(m[1] ?? 0) * 3600 + Number(m[2] ?? 0) * 60 + Number(m[3] ?? 0)) || null;
}

function cleanDescription(raw) {
  if (!raw) return "";
  const lines = raw
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter(
      (l) =>
        l.length > 24 &&
        !/https?:\/\//i.test(l) &&
        !/^(subscribe|follow|stream|buy|shop|check out|listen now|download)/i.test(l) &&
        !/#\w+(\s+#\w+)+\s*$/.test(l)
    );
  const text = lines.join(" ").replace(/\s+/g, " ").trim();
  return text.length > 420 ? text.slice(0, 417).trimEnd() + "…" : text;
}

const facts = {};
for (let i = 0; i < uniqueIds.length; i += 50) {
  const batch = uniqueIds.slice(i, i + 50);
  const url =
    "https://www.googleapis.com/youtube/v3/videos?part=contentDetails,snippet&id=" +
    batch.join(",") +
    "&key=" +
    apiKey;
  const res = await fetch(url);
  if (!res.ok) {
    console.error(`YouTube API HTTP ${res.status} on batch starting ${batch[0]}`);
    process.exit(1);
  }
  const data = await res.json();
  for (const item of data.items ?? []) {
    facts[item.id] = {
      durationSec: iso8601ToSeconds(item.contentDetails?.duration),
      publishedAt: (item.snippet?.publishedAt ?? "").slice(0, 10),
      description: cleanDescription(item.snippet?.description ?? ""),
    };
  }
}

const covered = Object.values(facts).filter((f) => f.durationSec).length;
console.log(`Facts fetched: ${Object.keys(facts).length}; with duration: ${covered}`);

const header = `/**
 * Song facts for the Mr Big Nuts chatbots — REAL data fetched from the
 * YouTube Data API v3 (duration, publish date, description) for every
 * video in the @TaylorMadeHits catalog.
 *
 * Generated by scripts/fetch-song-facts.mjs — do not hand-edit.
 * Generated: ${new Date().toISOString().slice(0, 10)}
 */
export interface SongFact {
  durationSec: number | null;
  publishedAt: string;
  description: string;
}

export const SONG_FACTS: Record<string, SongFact> = `;

writeFileSync(
  join(root, "src/data/songFacts.ts"),
  header + JSON.stringify(facts, null, 2) + ";\n"
);
console.log("Wrote src/data/songFacts.ts");
